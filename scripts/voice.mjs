// Render every radio line to public/voice/<key>.mp3 with ElevenLabs, and write src/voicelines.ts.
// Needs ELEVENLABS_API_KEY in the environment. Skips clips that already exist unless --force.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const lines = JSON.parse(readFileSync(resolve(here, "voicelines.json"), "utf8"));
const key = process.env.ELEVENLABS_API_KEY;
if (!key) { console.error("ELEVENLABS_API_KEY is not set"); process.exit(1); }
const force = process.argv.includes("--force");
const VOICES = { copilot: "pNInz6obpgDQGcFmaJgB", wingman: "iP95p4xoKVk53GoZ742B" }; // Adam (deep, dominant, American), Chris (down-to-earth, American)
const out = resolve(root, "public/voice");
mkdirSync(out, { recursive: true });

let made = 0, skipped = 0;
for (const [who, table] of Object.entries(lines)) {
  for (const [lineKey, variants] of Object.entries(table)) for (let vi = 0; vi < variants.length; vi++) {
    const text = variants[vi], id = `${lineKey}.${vi}`;
    const file = resolve(out, `${id}.mp3`);
    if (existsSync(file) && !force) { skipped++; continue; }
    const r = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICES[who]}?output_format=mp3_22050_32`, {
      method: "POST",
      headers: { "xi-api-key": key, "content-type": "application/json" },
      body: JSON.stringify({ text, model_id: "eleven_multilingual_v2", voice_settings: { stability: 0.4, similarity_boost: 0.85, style: 0.45, use_speaker_boost: true } }),
    });
    if (!r.ok) { console.error(id, r.status, await r.text()); process.exit(1); }
    writeFileSync(file, Buffer.from(await r.arrayBuffer()));
    made++; process.stdout.write(`${id} `);
  }
}
// the manifest the game reads: text -> clip id, so call sites keep their plain-text calls
const all = Object.assign({}, ...Object.values(lines));
const ts = `/* Generated by scripts/voice.mjs from scripts/voicelines.json. Do not edit by hand. */
/** every variant of every line, by event key */
export const VOICE_VARIANTS: Record<string, string[]> = ${JSON.stringify(all, null, 2)};
/** clip id for a line of text, if one was rendered */
export const CLIP_FOR: Record<string, string> = {};
for (const [k, vs] of Object.entries(VOICE_VARIANTS)) vs.forEach((v, i) => { CLIP_FOR[v] = k + "." + i; });
`;
writeFileSync(resolve(root, "src/voicelines.ts"), ts);
console.log(`\ndone: ${made} rendered, ${skipped} kept`);
