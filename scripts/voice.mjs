// Render every radio line to public/voice/<key>.mp3 with ElevenLabs, and write src/voicelines.ts.
// Needs ELEVENLABS_API_KEY in the environment. A clip is rendered when it is missing or its text
// changed (public/voice/manifest.json remembers what each clip says); --force re-renders everything.
// Clips whose line is gone from the script are deleted.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, unlinkSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const lines = JSON.parse(readFileSync(resolve(here, "voicelines.json"), "utf8"));
const key = process.env.ELEVENLABS_API_KEY;
if (!key) { console.error("ELEVENLABS_API_KEY is not set"); process.exit(1); }
const force = process.argv.includes("--force");
/* Three people on the net. Magic is the controller: calm, exact, the one who gives the orders
   (Sarah: mature, reassuring, American). Hook is the back seat: reactive, quick, not entirely
   respectful (Adam: deep, dominant, American). Two is the wingman (Chris: down-to-earth). */
const VOICES = { control: "EXAVITQu4vr4xnSDxMaL", copilot: "pNInz6obpgDQGcFmaJgB", wingman: "iP95p4xoKVk53GoZ742B" };
const SETTINGS = {
  control: { stability: 0.62, similarity_boost: 0.8, style: 0.2, use_speaker_boost: true },
  copilot: { stability: 0.4, similarity_boost: 0.85, style: 0.45, use_speaker_boost: true },
  wingman: { stability: 0.45, similarity_boost: 0.85, style: 0.35, use_speaker_boost: true },
};
const out = resolve(root, "public/voice");
mkdirSync(out, { recursive: true });
const manifestPath = resolve(out, "manifest.json");
const manifest = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, "utf8")) : {};

let made = 0, skipped = 0, removed = 0;
const wanted = new Set();
for (const [who, table] of Object.entries(lines)) {
  for (const [lineKey, variants] of Object.entries(table)) for (let vi = 0; vi < variants.length; vi++) {
    const text = variants[vi], id = `${lineKey}.${vi}`;
    const file = resolve(out, `${id}.mp3`);
    wanted.add(`${id}.mp3`);
    if (existsSync(file) && manifest[id] === text && !force) { skipped++; continue; }
    const r = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICES[who]}?output_format=mp3_22050_32`, {
      method: "POST",
      headers: { "xi-api-key": key, "content-type": "application/json" },
      body: JSON.stringify({ text, model_id: "eleven_multilingual_v2", voice_settings: SETTINGS[who] }),
    });
    if (!r.ok) { console.error(id, r.status, await r.text()); process.exit(1); }
    writeFileSync(file, Buffer.from(await r.arrayBuffer()));
    manifest[id] = text;
    writeFileSync(manifestPath, JSON.stringify(manifest, null, 1));
    made++; process.stdout.write(`${id} `);
  }
}
for (const f of readdirSync(out)) if (f.endsWith(".mp3") && !wanted.has(f)) { unlinkSync(resolve(out, f)); delete manifest[f.replace(/\.mp3$/, "")]; removed++; }
writeFileSync(manifestPath, JSON.stringify(manifest, null, 1));
// the manifest the game reads: text -> clip id, so call sites keep their plain-text calls, and who says what
const all = Object.assign({}, ...Object.values(lines));
const who = {};
for (const [w, table] of Object.entries(lines)) for (const k of Object.keys(table)) who[k] = w;
const ts = `/* Generated by scripts/voice.mjs from scripts/voicelines.json. Do not edit by hand. */
/** every variant of every line, by event key */
export const VOICE_VARIANTS: Record<string, string[]> = ${JSON.stringify(all, null, 2)};
/** who says each line: the controller, the back seat, or the wingman */
export type Speaker = "control" | "copilot" | "wingman";
export const VOICE_WHO: Record<string, Speaker> = ${JSON.stringify(who, null, 2)} as Record<string, Speaker>;
/** clip id for a line of text, if one was rendered */
export const CLIP_FOR: Record<string, string> = {};
for (const [k, vs] of Object.entries(VOICE_VARIANTS)) vs.forEach((v, i) => { CLIP_FOR[v] = k + "." + i; });
`;
writeFileSync(resolve(root, "src/voicelines.ts"), ts);
console.log(`\ndone: ${made} rendered, ${skipped} kept, ${removed} removed`);
